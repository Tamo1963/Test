"""Generate / run the FreeCAD build script for a design."""
from __future__ import annotations

import json
import pathlib
import shutil
import subprocess
import tempfile

BODY = pathlib.Path(__file__).with_name('freecad_body.py')


def make_script(cp: dict, out_dir: str = '/tmp/adm_cstr_cad') -> str:
    header = ('# Generated by adm_cstr_designer. Dimensions in metres.\n'
              f'PARAMS = {json.dumps(cp, indent=2)}\n'
              f'OUT_DIR = {out_dir!r}\n\n')
    return header + BODY.read_text()


def freecad_executable() -> str | None:
    for n in ('freecadcmd', 'FreeCADCmd', 'freecad.cmd'):
        p = shutil.which(n)
        if p:
            return p
    return None


def run_freecad(cp: dict, out_dir: str) -> dict:
    exe = freecad_executable()
    if not exe:
        return dict(ok=False, message='FreeCAD command-line (freecadcmd) not found on this machine.')
    out = pathlib.Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    script = out / 'build_cstr.py'
    script.write_text(make_script(cp, str(out)))
    r = subprocess.run([exe, str(script)], capture_output=True, text=True, timeout=300)
    files = {p.name: p for p in out.iterdir() if p.suffix.lower() in ('.fcstd', '.step', '.stl')}
    return dict(ok=bool(files), message=(r.stdout + r.stderr)[-1500:], files=files, script=script)
